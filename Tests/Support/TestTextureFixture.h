#pragma once

#include <array>
#include <cstdint>
#include <filesystem>
#include <fstream>

namespace HE::Tests {
	inline bool WriteTinyPng(const std::filesystem::path& path) {
		constexpr std::array<uint8_t, 75> pngBytes = {
			0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A,
			0x00, 0x00, 0x00, 0x0D, 0x49, 0x48, 0x44, 0x52,
			0x00, 0x00, 0x00, 0x02, 0x00, 0x00, 0x00, 0x02,
			0x08, 0x06, 0x00, 0x00, 0x00, 0x72, 0xB6, 0x0D,
			0x24, 0x00, 0x00, 0x00, 0x12, 0x49, 0x44, 0x41,
			0x54, 0x78, 0x9C, 0x63, 0xF8, 0xCF, 0xC0, 0xF0,
			0x1F, 0x0C, 0x81, 0x34, 0x18, 0x00, 0x00, 0x49,
			0xC8, 0x09, 0xF7, 0xF9, 0xAB, 0xB6, 0x0D, 0x00,
			0x00, 0x00, 0x00, 0x49, 0x45, 0x4E, 0x44, 0xAE,
			0x42, 0x60, 0x82
		};

		std::error_code errorCode;
		std::filesystem::create_directories(path.parent_path(), errorCode);
		if (errorCode)
			return false;

		std::ofstream output(path, std::ios::binary | std::ios::trunc);
		output.write(
			reinterpret_cast<const char*>(pngBytes.data()),
			static_cast<std::streamsize>(pngBytes.size()));
		return output.good();
	}
}
